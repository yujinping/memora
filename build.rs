//! 构建脚本：把 Vue 控制台的构建产物整理成可内嵌的 Rust 资源清单。
//!
//! @author yujinping
//! @intent 单二进制发布要求前端产物**编进可执行文件**，而 `include_bytes!` 只能接
//!         编译期已知的路径。Vite 的产物文件名带内容哈希（`index-a1b2c3d4.js`），
//!         无法在源码里写死；因此在构建脚本里扫目录、生成一份清单源文件，
//!         再由 `console` 模块 `include!` 进来。
//!
//! @intent 产物目录 `src/console_dist/` **入库**（而非构建时生成）。理由：
//!         `cargo build` 是 Rust 用户唯一该有的先决条件；若它要求先装 node + pnpm，
//!         那么「只改后端一个字符串」也要拉起整条前端工具链——这会把本项目的
//!         构建门槛从「有 cargo」抬到「有 cargo 且有前端环境」。
//!         产物入库的代价是可能与 `web/` 源码漂移，由 `scripts/build-web.sh`
//!         一条命令重新生成，并在 README 里写明。
//!
//! @intent 目录缺失时**直接报告并指出修复命令**，而不是静默内嵌一个占位页：
//!         占位页会让服务正常启动、控制台打开却是一片空白，而构建日志里只有
//!         一个 warning——属于「能跑但坏了」的最坏形态。编译期失败在这里是优点。

use std::fs;
use std::path::{Path, PathBuf};

/// 前端产物目录（相对 crate 根）。
const DIST_DIR: &str = "src/console_dist";

/// 入口文件（其余文件按路径登记为静态资源）。
const ENTRY: &str = "index.html";

fn main() {
    println!("cargo:rerun-if-changed={DIST_DIR}");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist = manifest_dir.join(DIST_DIR);
    let entry = dist.join(ENTRY);

    if !entry.is_file() {
        panic!(
            "\n\n未找到前端构建产物：{}\n\
             控制台产物随仓库提供，若此处缺失说明工作树不完整；\n\
             重新生成请运行：scripts/build-web.sh（需要 node 18+ 与 pnpm）\n\n",
            entry.display()
        );
    }

    let mut assets: Vec<(String, PathBuf)> = Vec::new();
    collect(&dist, &dist, &mut assets);
    // 路径排序：清单是静态数组，顺序稳定才能让「新增一个文件」在 diff 里只多一行。
    assets.sort_by(|a, b| a.0.cmp(&b.0));

    let mut generated = String::with_capacity(assets.len() * 256 + 512);
    generated.push_str(
        "// @generated by build.rs —— 请勿手工编辑。\n\
         // 内容来自 src/console_dist/，重新生成：scripts/build-web.sh\n\n",
    );

    generated.push_str("/// SPA 入口页面。\n");
    generated.push_str(&format!(
        "pub static INDEX_HTML: &[u8] = include_bytes!({:?});\n\n",
        entry.display().to_string()
    ));

    generated.push_str("/// 除入口页面外的全部静态资源。\n");
    generated.push_str("pub static ASSETS: &[crate::console::Asset] = &[\n");
    for (relative, absolute) in &assets {
        if relative == ENTRY {
            continue;
        }
        generated.push_str(&format!(
            "    crate::console::Asset {{\n        path: {relative:?},\n        \
             bytes: include_bytes!({absolute:?}),\n        content_type: {mime:?},\n        \
             immutable: {immutable},\n    }},\n",
            absolute = absolute.display().to_string(),
            mime = mime_of(relative),
            immutable = is_immutable(relative),
        ));
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("console_assets.rs");
    fs::write(&out, generated).expect("cannot write the generated asset manifest");
}

/// 递归收集文件，路径统一为相对 `dist` 的 `/` 分隔形式。
fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(err) => panic!("无法读取前端产物目录 {}：{err}", dir.display()),
    };

    for entry in entries {
        let path = entry.expect("cannot read a directory entry").path();
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .expect("collected path must live under the dist root")
            .to_string_lossy()
            .replace('\\', "/");
        // 构建脚本自身会重跑，故每次文件变化都要单独登记。
        println!("cargo:rerun-if-changed={}", path.display());
        out.push((relative, path));
    }
}

/// 按扩展名给出 MIME。
///
/// @intent 手写映射而不引三方库：产物只有 html / js / css / svg / ico / png 这几种，
///         为一次查表引入 `mime_guess` 与它带来的几百 KB 编译量不值当。
///         未识别的扩展名回落 `application/octet-stream`——它会让浏览器**下载**
///         而非执行，是安全的失败方向。
fn mime_of(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or_default() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "application/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

/// 文件名是否含内容哈希（可永久缓存）。
///
/// @intent 判据锚定 Vite 的默认布局：带哈希的产物一定在 `assets/` 下，而固定名字的
///         文件（`index.html`、`favicon.ico`）在根上。不按「文件名里有没有
///         8 位十六进制」猜——那种判据在哈希长度变化时会静默失效，
///         失效的后果是把可缓存的资源降级为 `no-store`（只是浪费带宽），
///         但反过来判断错了就是升级后白屏。
fn is_immutable(path: &str) -> bool {
    path.starts_with("assets/")
}